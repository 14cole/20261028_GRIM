"""Make review tables and CSV from completed, analyzed evidence."""
import csv,json
from collections import Counter
from pathlib import Path
P=Path(__file__).resolve().parent
d=json.loads((P/'SUMMARY.json').read_text());rows=d['rows'];by={r['case']:r for r in rows}
declared=[]
for name in ('catalog','investigation-catalog'):
    declared+=json.loads((P/(name+'.json')).read_text())
assert len({r['case'] for r in declared})==len(declared)
assert set(by)=={r['case'] for r in declared},(set(by)^{r['case'] for r in declared})
expected=json.loads((P/'SOURCE_IDENTITY.json').read_text())['source_sha256']
for r in rows:
    raw=json.loads((P/'results'/(r['case']+'.json')).read_text())
    if 'source_sha256' in raw:
        if raw['source_sha256']!=expected:
            # Early explicit-mode runs preceded a timer-only Automatic retry fix.
            assert raw['source_sha256']=='dc37e91c015799885dd0d1529ffbe5770147ee3381b100726ba34659ab7ffbe2',r['case']
            assert raw['spec']['backend'] in ('dense','compressed') and raw['spec']['group'] in ('control','scaling'),r['case']
    if r['status']=='success':assert r['quality_passed']
    if r['spec'].get('full_fallback') or r['spec'].get('fallback'):
        assert r['children']==0,'Fallback monkeypatch is in-process only: '+r['case']
keys=['case','group','backend','status','actual_panels','actual_unknowns','matrix_floor_gib','wall_seconds','peak_tree_rss_gib','peak_parent_rss_gib','forecast_gib','mesh_certified','quality_passed','condition_est_max','residual_norm_max','error']
with (P/'RESULTS.csv').open('w') as f:
    w=csv.DictWriter(f,keys,extrasaction='ignore');w.writeheader();w.writerows(rows)
out=['# Complete stress-suite results','',
     'Generated by `export_results.py` from `SUMMARY.json`. All declared cases must have a recorded outcome. GiB = 2^30 bytes. Times are solve wall times, excluding imports; RSS is the peak sampled sum across the process tree (shared pages may be counted in multiple processes). Timing runs were sequential, with four CPUs allocated. These are individual observations, not a statistical performance guarantee.','',
     f"{len(rows)} cases: {dict(Counter(r['status'] for r in rows))}. Certified successes: {sum(r['mesh_certified'] for r in rows)}.",'',
     '## Every case','',
     '| Case | Outcome | Unknowns | Seconds | Tree GiB | Forecast GiB | Certified |',
     '|---|---|---:|---:|---:|---:|---|']
for r in rows:
    out.append(f"| {r['case']} | {r['status']} | {r['actual_unknowns']:,} | {r['wall_seconds']:.2f} | {r['peak_tree_rss_gib']:.3f} | {r['forecast_gib']:.3f} | {'yes' if r['mesh_certified'] else 'no'} |")
out+=['','Forecast is the largest captured execution plan. A retry may create several plans; inspect raw events to associate a phase with its plan. A whole-call RSS peak must not be compared solely with a later retry plan. Refusal runtime/RSS is not a solve benchmark.','',
      '## Complete-field Dense/compressed comparisons','',
      'The metric is max(abs(Dense − compressed)) / max(abs(Dense)) across every returned complex field. This avoids division by scattering nulls. It is backend agreement on the tested mesh, not an independent certificate of continuum accuracy.','',
      '| Geometry | Dense outcome | Compressed outcome | Fields | Normalized max difference | Same unknown count |',
      '|---|---|---|---:|---:|---|']
for p in d['pairs']:
    error=p.get('relative_max_field_difference')
    out.append(f"| {p['geometry_id']} | {p['dense_status']} | {p['compressed_status']} | {p.get('fields','—')} | {error:.3e} | {p.get('mesh_unknowns_match','—')} |" if error is not None else f"| {p['geometry_id']} | {p['dense_status']} | {p['compressed_status']} | — | — | — |")
out+=['','## Controlled experiments','',
      'Ratios are experiment/reference; lower is faster/smaller. References are named exactly. Polynomial controls deliberately change the mesh basis and are not identical-system performance comparisons. Research hooks are identified in each specification.','',
      '| Experiment | Reference | Status | Time ratio | RSS ratio | Max field difference |',
      '|---|---|---|---:|---:|---:|']
for e in d['experiments']:
    diff=e.get('relative_max_field_difference')
    out.append(f"| {e['case']} | {e['reference']} | {e['status']} | {e.get('time_ratio',0):.3f} | {e.get('tree_rss_ratio',0):.3f} | {diff:.3e} |" if diff is not None else f"| {e['case']} | {e['reference']} | {e['status']} | — | — | — |")
out+=['','## Independent cylinder-series comparisons','',
      'Closed-form circular-cylinder series are implemented in the pinned repository validation module. They do not use the boundary-integral assembly. The solver geometry is polygonal. Width/dB checks cover PEC, dielectric and PEC-backed single coatings; PEC also has complex-amplitude checks. There is no analytic reference here for junctions, combs, multilayer or star geometries.','',
      '| Case | Polarization | Max dB error | Reference valid |',
      '|---|---|---:|---|']
for a in d['analytic']:
    for pol,v in a['polarizations'].items():
        err=v.get('max_db_error')
        out.append(f"| {a['case']} | {pol} | {err:.6g} | yes |" if err is not None else f"| {a['case']} | {pol} | — | no: {v.get('error','nonfinite reference')} |")
out+=['','## All unsuccessful outcomes','']
for r in rows:
    if r['status']!='success':out += [f"### {r['case']}",'',r['error'],'']
out+=['## 32 GiB desktop capacity forecast — not measured solves','',
      'Assumptions: 24 GiB reserved for one solve, four CPUs, adequate disk-backed scratch. Exact captured meshes are repriced with the production estimator. The two fit columns are different: `predicted payload fits` is not a general execution-admission veto. This is a screening forecast, not proof that a permitted construction will finish or that a refused one is physically impossible.','',
      '| Case | Unknowns | One dense matrix GiB | Forecast GiB | Peak fits 24 GiB | Predicted payload fits |',
      '|---|---:|---:|---:|---|---|']
for r in json.loads((P/'FORECAST_32GIB.json').read_text())['rows']:
    out.append(f"| {r['case']} | {r['unknowns']:,} | {r['matrix_gib']:.2f} | {r['forecast_gib']:.2f} | {r['peak_fits']} | {r['predicted_payload_fits']} |")
(P/'RESULTS.md').write_text('\n'.join(out)+'\n')
print('Verified and exported',len(rows),'cases')
