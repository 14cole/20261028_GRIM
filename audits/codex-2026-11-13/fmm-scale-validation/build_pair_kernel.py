"""Research paired-panel ABI; reject upstream source drift before compiling."""
import os,re,subprocess
from pathlib import Path

def derive(source):
    marker='/* Tile scatter'
    if source.count(marker)!=1:raise ValueError('Expected one far/scatter boundary')
    text=source.split(marker)[0]
    # Definition and call sites are checked separately; these identifiers occur
    # more than once by design. Every structural loop replacement occurs once.
    for token,count in [('ghost_far_block_impl',5),('ghost_far_block',1)]:
        pattern=r'\b'+token+r'\b'
        if len(re.findall(pattern,text))!=count:raise ValueError('Unexpected occurrences of '+token)
        text=re.sub(pattern,token.replace('ghost_far','ghost_pair'),text)
    replacements=[('int64_t plane = mb * nb;','int64_t plane = mb;'),
                  ('for (int64_t j = 0; j < nb; ++j)','for (int64_t j = i; j < i + 1; ++j)'),
                  ('int64_t pair = i * nb + j;','int64_t pair = i;')]
    for old,new in replacements:
        if text.count(old)!=1:raise ValueError('Expected one occurrence of '+old)
        text=text.replace(old,new,1)
    return '/* RESEARCH paired-panel variant; generated by build_pair_kernel.py. */\n'+text

if __name__=='__main__':
    root=Path(os.environ['GRIM_ROOT'])/'tools/GHOST/ghost_backend/twod/assembly/native'
    source=derive((root/'far.c').read_text())
    Path('paired_kernel.c').write_text(source)
    subprocess.run(['cc','-O3','-std=c99','-ffp-contract=off','-fPIC','-shared','paired_kernel.c','-o','libpaired_kernel.so','-lm'],check=True)
