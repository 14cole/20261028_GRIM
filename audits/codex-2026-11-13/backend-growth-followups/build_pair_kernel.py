"""Research only: derive a paired-panel ABI from the existing far kernel."""
import os,subprocess
from pathlib import Path
root=Path(os.environ['GRIM_ROOT'])/'tools/GHOST/ghost_backend/twod/assembly/native'
s=(root/'far.c').read_text().split('/* Tile scatter')[0]
s=s.replace('ghost_far_block','ghost_pair_block').replace('int64_t plane = mb * nb;','int64_t plane = mb;').replace('for (int64_t j = 0; j < nb; ++j)', 'for (int64_t j = i; j < i + 1; ++j)').replace('int64_t pair = i * nb + j;','int64_t pair = i;')
Path('paired_kernel.c').write_text('/* RESEARCH paired-panel variant; generated by build_pair_kernel.py. */\n'+s)
subprocess.run(['cc','-O3','-std=c99','-ffp-contract=off','-fPIC','-shared','paired_kernel.c','-o','libpaired_kernel.so','-lm'],check=True)
